#!/usr/bin/env python3
"""Generate a replay check file from a known-good run.

The run is described either by a watch trace (sa1psp --watch-list
tests/replay/watch.txt --watch-trace run.tsv: every watched value on every
frame) or by RAM dumps (sa1psp --dump FRAME:FILE; the frame is the last
number in each file name).  The trace is the better input: milestones are
then exact to the frame.

  tape_expect.py --trace run.tsv -o tests/replay/title.check
  tape_expect.py --dumps dumps/ram_*.bin -o out.check

Check rows (backend/desktop/input_tape.c, tests/replay/README.md):
  FRAME ADDR SIZE EXPECTED [TOLERANCE] [NAME]
Primary rows are milestones: each lasting change of a "milestone" watch
(game mode, level, act) becomes "this value at some frame in
F-slack..F+slack", so a legitimate HLE change that shifts timing a little
does not fail the tape.  Secondary rows ("[secondary]") sample the "exact"
watches every --every frames; the runner reports them as drift.

Part of sa1-psp (MIT).
"""
import argparse
import os
import re
import struct
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
DEFAULT_WATCH = os.path.join(ROOT, "tests", "replay", "watch.txt")


class Watch:
    def __init__(self, addr, size, name, role, tol):
        self.addr, self.size, self.name, self.role, self.tol = addr, size, name, role, tol

    def is_float(self):
        return self.size == "f"

    def fmt(self, v):
        if self.is_float():
            return "%.9g" % v
        return str(int(v))


def read_watch(path):
    out = []
    with open(path, encoding="utf-8") as f:
        for n, line in enumerate(f, 1):
            line = line.split("#", 1)[0].split()
            if not line:
                continue
            if len(line) < 3:
                sys.exit("%s:%d: need ADDR SIZE NAME [ROLE [TOLERANCE]]" % (path, n))
            role = line[3] if len(line) > 3 else "exact"
            if role not in ("milestone", "exact", "trace"):
                sys.exit("%s:%d: role must be milestone, exact or trace" % (path, n))
            tol = float(line[4]) if len(line) > 4 else 0.0
            out.append(Watch(int(line[0], 16), line[1], line[2], role, tol))
    return out


def read_trace(path, watches):
    """{frame: {name: value}} from a --watch-trace file."""
    rows = {}
    with open(path, encoding="utf-8") as f:
        header = f.readline().rstrip("\n").split("\t")
        if not header or header[0] != "frame":
            sys.exit("%s: not a watch trace (first column must be 'frame')" % path)
        for line in f:
            cells = line.rstrip("\n").split("\t")
            if len(cells) != len(header):
                continue                      # a truncated last line (crash)
            rows[int(cells[0])] = {h: float(c) for h, c in zip(header[1:], cells[1:])}
    missing = [w.name for w in watches if rows and w.name not in next(iter(rows.values()))]
    if missing:
        sys.exit("%s: no column for %s (traced with another watch list?)" % (path, ", ".join(missing)))
    return rows


SIZE_FMT = {"1": "<B", "2": "<H", "4": "<I", "s1": "<b", "s2": "<h", "s4": "<i", "f": "<f"}


def read_dumps(paths, watches):
    rows = {}
    for p in paths:
        m = re.findall(r"\d+", os.path.basename(p))
        if not m:
            sys.exit("%s: no frame number in the file name" % p)
        frame = int(m[-1])
        with open(p, "rb") as f:
            data = f.read()
        vals = {}
        for w in watches:
            off = w.addr & 0x00FFFFFF
            vals[w.name] = float(struct.unpack_from(SIZE_FMT[w.size], data, off)[0])
        rows[frame] = vals
    return rows


def milestones(rows, watches, settle):
    """[(frame, watch, value)]: each change of a milestone watch's value that
    then holds for at least `settle` frames of the run."""
    frames = sorted(rows)
    out = []
    for w in (w for w in watches if w.role == "milestone"):
        cur = None
        i = 0
        while i < len(frames):
            v = rows[frames[i]][w.name]
            if v != cur:
                j = i
                while j < len(frames) and rows[frames[j]][w.name] == v:
                    j += 1
                held = (frames[j - 1] - frames[i]) if j > i else 0
                if held >= settle or j == len(frames):
                    out.append((frames[i], w, v))
                    cur = v
                i = j
            else:
                i += 1
    out.sort(key=lambda t: (t[0], t[1].name))
    return out


def generate(rows, watches, slack, slack_pct, every, settle, source):
    if not rows:
        sys.exit("no frames in the run")
    frames = sorted(rows)
    last = frames[-1]
    lines = ["# generated by tools/tape_expect.py from %s" % source,
             "# frames %d..%d; milestone slack %d + %g%%; secondary every %d frames"
             % (frames[0], last, slack, slack_pct, every),
             "# FRAME ADDR SIZE EXPECTED [TOLERANCE] [NAME]",
             "[primary]"]
    for frame, w, v in milestones(rows, watches, settle):
        s = slack + int(frame * slack_pct / 100)
        lines.append("%d..%d %08x %s %s - %s@%d" % (max(1, frame - s), frame + s, w.addr, w.size, w.fmt(v), w.name, frame))
    exact = [w for w in watches if w.role == "exact"]
    if exact:
        lines.append("[secondary]")
        sample = [f for f in frames if f % every == 0]
        if last not in sample:
            sample.append(last)
        for f in sample:
            for w in exact:
                tol = ("%g" % w.tol) if w.tol else "-"
                lines.append("%d %08x %s %s %s %s" % (f, w.addr, w.size, w.fmt(rows[f][w.name]), tol, w.name))
    return "\n".join(lines) + "\n"


def main(argv=None):
    ap = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    src = ap.add_mutually_exclusive_group(required=True)
    src.add_argument("--trace", help="watch trace (sa1psp --watch-trace)")
    src.add_argument("--dumps", nargs="+", help="RAM dumps (sa1psp --dump), frame = last number in the name")
    ap.add_argument("--watch", default=DEFAULT_WATCH, help="watch list (default tests/replay/watch.txt)")
    ap.add_argument("--slack", type=int, default=300, help="milestone window half-width in frames (default 300)")
    ap.add_argument("--slack-pct", type=float, default=2.0, help="plus this percent of the frame number (default 2)")
    ap.add_argument("--every", type=int, default=600, help="secondary sample interval in frames (default 600)")
    ap.add_argument("--settle", type=int, default=30, help="ignore milestone values held fewer frames (default 30)")
    ap.add_argument("-o", "--out", help="output check file (default stdout)")
    a = ap.parse_args(argv)
    watches = read_watch(a.watch)
    if a.trace:
        rows, source = read_trace(a.trace, watches), os.path.basename(a.trace)
    else:
        rows, source = read_dumps(a.dumps, watches), "%d dumps" % len(a.dumps)
    text = generate(rows, watches, a.slack, a.slack_pct, a.every, a.settle, source)
    if a.out:
        with open(a.out, "w", encoding="utf-8", newline="\n") as f:
            f.write(text)
    else:
        sys.stdout.write(text)
    return 0


if __name__ == "__main__":
    sys.exit(main())
