#!/usr/bin/env python3
"""Generate hle/overlay/overlay_registry.c from the overlay configs.

Usage:
  gen_overlay_registry.py [--check]

Reads the [sa1_overlay] table of every recomp/sa1_us_1005/overlays/*.toml
(file, slot, size, sha256) and writes one hle_overlay_file record per
overlay, pointing at the sa1_ovl_<name> table that
recomp/emitter/emit_overlay.py generates.  The output holds only names,
addresses, sizes and hashes; nothing from the disc.  --check exits 1 if the
committed file is out of date instead of writing it.
"""
from __future__ import annotations

import glob
import os
import sys
import tomllib

REPO = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
CONFIGS = os.path.join(REPO, "recomp", "sa1_us_1005", "overlays")
OUT = os.path.join(REPO, "hle", "overlay", "overlay_registry.c")
SLOTS = {0x0C900000: "SA1_SLOT_AREA", 0x0CB80000: "SA1_SLOT_EVENT"}


def records():
    out = []
    for path in sorted(glob.glob(os.path.join(CONFIGS, "*.toml"))):
        with open(path, "rb") as f:
            ov = tomllib.load(f).get("sa1_overlay")
        if ov is None:
            continue
        name = os.path.splitext(os.path.basename(path))[0]
        slot = SLOTS.get(ov["slot"] & 0x1FFFFFFF)
        if slot is None:
            sys.exit("%s: slot 0x%08x has no runtime slot" % (path, ov["slot"]))
        out.append((name, ov["file"], slot, ov["size"], ov["sha256"]))
    return out


def render(recs):
    L = ["/* generated by tools/gen_overlay_registry.py from",
         " * recomp/sa1_us_1005/overlays/<name>.toml; do not edit.  One record per",
         " * recompiled code overlay; the sa1_ovl_* tables come from",
         " * recomp/emitter/emit_overlay.py (recomp/out/, never committed). */",
         '#include "overlay_loader.h"', ""]
    L.append("extern const sa1_overlay %s;" % ", ".join("sa1_ovl_" + r[0] for r in recs))
    L += ["", "const hle_overlay_file hle_overlay_files[] = {"]
    width = max(len(r[1]) for r in recs) + 3
    for name, file, slot, size, sha in recs:
        L.append('    {%-*s %-15s %8d, "%s", &sa1_ovl_%s},' % (width, '"%s",' % file, slot + ",", size, sha, name))
    L += ["};", "const unsigned hle_overlay_file_count = %d;" % len(recs), ""]
    return "\n".join(L)


def main(argv):
    text = render(records())
    if argv and argv[0] == "--check":
        try:
            with open(OUT, encoding="utf-8") as f:
                same = f.read() == text
        except FileNotFoundError:
            same = False
        print("%s is %s" % (os.path.relpath(OUT, REPO).replace("\\", "/"), "up to date" if same else "out of date"))
        return 0 if same else 1
    with open(OUT, "w", encoding="utf-8", newline="\n") as f:
        f.write(text)
    print("wrote %s" % os.path.relpath(OUT, REPO).replace("\\", "/"))
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
