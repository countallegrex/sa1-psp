#!/usr/bin/env python3
"""Refuse to commit anything that looks like game data or game-derived code.

Usage:
  check_clean.py            check files staged for commit (pre-commit hook)
  check_clean.py --all      check every tracked file (run before going public)
  check_clean.py PATH...    check the given files

Exit status 0 = clean, 1 = something was refused (reasons printed).
"""
from __future__ import annotations

import os
import shutil
import subprocess
import sys

REPO = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))


def git_exe() -> str:
    found = shutil.which("git")
    if found:
        return found
    for candidate in (
        r"C:\Program Files\Git\cmd\git.exe",
        r"C:\Program Files (x86)\Git\cmd\git.exe",
        "/usr/bin/git",
    ):
        if os.path.isfile(candidate):
            return candidate
    sys.exit("check_clean: git not found on PATH")

# Extensions of Dreamcast disc content and PSP build products.
BLOCKED_EXT = {
    ".gdi", ".cdi", ".bin", ".raw", ".prs", ".pvr", ".pvm", ".adx", ".afs",
    ".mlt", ".mpb", ".msb", ".sfd", ".aif", ".pbp", ".prx", ".elf", ".o",
    ".obj", ".a", ".lib",
}

# Paths that may never contain committed files.
BLOCKED_DIRS = ("recomp/out/", "private/", "assets_out/", "ms0/", "toolchain/")

# Byte signatures of Dreamcast/Katana/CRI material.
SIGNATURES = [
    (b"SEGA SEGAKATANA", "Dreamcast IP.BIN header"),
    (b"Lib Handle Start", "Katana SDK startup stub (1ST_READ.BIN)"),
    (b"PVRT", "PowerVR texture"),
    (b"GBIX", "PowerVR texture global index"),
    (b"(c)CRI", "CRI ADX/AFS/Sofdec"),
    (b"AFS\x00", "CRI AFS archive"),
    (b"SMLT", "Manatee sound bank"),
    (b"~PSP", "PSP module header (built EBOOT/PRX)"),
    (b"\x00PBP", "PSP EBOOT container"),
]

# Any committed file bigger than this is suspicious for a source repo.
MAX_BYTES = 512 * 1024

# Recompiled game code is recognisable by the emitter's own markers; add the
# chosen emitter's banner here once M0 picks one.
GENERATED_MARKERS = [
    b"// Generated by dream-translate",  # Dream-Recomp's actual banner (measured at M0)
    b"/* Generated by Dream-Recomp",
    b"// Generated by dcrecomp",
    b"SA1_RECOMP_GENERATED",
]


def staged_files() -> list[str]:
    out = subprocess.run(
        [git_exe(), "diff", "--cached", "--name-only", "--diff-filter=ACMR"],
        cwd=REPO, capture_output=True, text=True, check=True,
    ).stdout
    return [l for l in out.splitlines() if l.strip()]


def tracked_files() -> list[str]:
    out = subprocess.run([git_exe(), "ls-files"], cwd=REPO,
                         capture_output=True, text=True, check=True).stdout
    return [l for l in out.splitlines() if l.strip()]


def check(rel: str) -> list[str]:
    reasons: list[str] = []
    norm = rel.replace("\\", "/")
    for d in BLOCKED_DIRS:
        if norm.startswith(d) or f"/{d}" in norm:
            reasons.append(f"path under blocked directory '{d}'")
    ext = os.path.splitext(norm)[1].lower()
    if ext in BLOCKED_EXT:
        reasons.append(f"blocked extension '{ext}'")
    path = os.path.join(REPO, rel)
    if not os.path.isfile(path):
        return reasons
    size = os.path.getsize(path)
    if size > MAX_BYTES:
        reasons.append(f"{size} bytes exceeds {MAX_BYTES} byte limit")
    with open(path, "rb") as f:
        head = f.read(4 * 1024 * 1024)
    if norm != "tools/check_clean.py":
        for sig, what in SIGNATURES:
            if sig in head:
                reasons.append(f"contains signature for {what}")
        for marker in GENERATED_MARKERS:
            if marker in head:
                reasons.append("looks like recompiled game code")
    return reasons


def main(argv: list[str]) -> int:
    if argv and argv[0] == "--all":
        files = tracked_files()
    elif argv:
        files = [os.path.relpath(os.path.abspath(a), REPO) for a in argv]
    else:
        files = staged_files()
    bad = 0
    for rel in files:
        reasons = check(rel)
        if reasons:
            bad += 1
            print(f"REFUSED {rel}")
            for r in reasons:
                print(f"    - {r}")
    if bad:
        print(f"\n{bad} file(s) refused. Nothing game-derived may enter this repo.")
        return 1
    print(f"clean: {len(files)} file(s) checked")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
